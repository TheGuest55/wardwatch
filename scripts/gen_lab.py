#!/usr/bin/env python3
"""Generate the lab from config/ward.json — the single source of truth.

Writes (all git-ignored, regenerated on `make up`):
  - docker-compose.yml           full stack: broker, nurse, N beds x 3 devices, capture, attacker
  - services/broker/acl          per-account topic ACLs
  - services/broker/accounts.txt one MQTT username per line (read by gen_passwd.sh)
  - .env                         one throwaway password per account (existing values preserved)

Host-side only, standard library only (this VM's Python has no third-party packages).
"""
import json
import os
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "config" / "ward.json"


def env_var(username):
    """MQTT username -> environment variable holding its password."""
    return "MQTT_PASS_" + username.upper().replace("-", "_")


def build_hosts(cfg):
    """Return the full host list: broker and attacker are infra; the rest are MQTT accounts."""
    prefix = cfg["network"]["subnet"].rsplit(".", 1)[0] + "."
    hosts = [{"name": "nurse-station", "role": "nurse-station", "ip": cfg["nurse"]["ip"],
              "bed": 0, "account": True}]
    for bed in range(1, cfg["beds"] + 1):
        base = 10 * bed
        rec = cfg["bidmc_records"].get(str(bed), "01")
        hosts.append({"name": f"bed{bed}-monitor", "role": "patient-monitor",
                      "ip": f"{prefix}{base + 1}", "bed": bed, "account": True, "bidmc": rec})
        hosts.append({"name": f"bed{bed}-pump", "role": "infusion-pump",
                      "ip": f"{prefix}{base + 2}", "bed": bed, "account": True})
        hosts.append({"name": f"bed{bed}-wearable", "role": "wearable",
                      "ip": f"{prefix}{base + 3}", "bed": bed, "account": True, "bidmc": rec})
    return hosts


def write_env(accounts):
    """Create/update .env, preserving any password already set so creds stay stable.
    Returns the {username: password} map."""
    env_path = ROOT / ".env"
    existing = {}
    if env_path.exists():
        for line in env_path.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                existing[k.strip()] = v
    lines = ["# Generated by scripts/gen_lab.py. Throwaway lab passwords, one per MQTT account.",
             "# Git-ignored. Delete a line to rotate that account's password on next `make up`."]
    mapping = {}
    for acc in accounts:
        var = env_var(acc)
        pw = existing.get(var) or secrets.token_urlsafe(16)
        mapping[acc] = pw
        lines.append(f"{var}={pw}")
    env_path.write_text("\n".join(lines) + "\n")
    return mapping


def write_creds(mapping):
    """Write the provisioned creds the attacker mounts (testbed artifice: seeds the bruteforce
    wordlist and is the fallback for credential-abuse). Git-ignored under data/."""
    d = ROOT / "data" / "raw" / "creds"
    d.mkdir(parents=True, exist_ok=True)
    (d / "accounts.json").write_text(json.dumps(mapping, indent=2))


def write_accounts(accounts):
    (ROOT / "services" / "broker" / "accounts.txt").write_text("\n".join(accounts) + "\n")


def write_acl(hosts, beds):
    lines = ["# Generated by scripts/gen_lab.py. Each device writes only its own topics;",
             "# only the nurse station may publish pump commands.", "",
             "user nurse-station", "topic read ward1/#", "topic write ward1/+/pump/cmd", ""]
    for h in hosts:
        if h["role"] == "patient-monitor":
            lines += [f"user {h['name']}", f"topic write ward1/bed{h['bed']}/monitor/#", ""]
        elif h["role"] == "infusion-pump":
            lines += [f"user {h['name']}",
                      f"topic write ward1/bed{h['bed']}/pump/telemetry/#",
                      f"topic read ward1/bed{h['bed']}/pump/cmd", ""]
        elif h["role"] == "wearable":
            lines += [f"user {h['name']}", f"topic write ward1/bed{h['bed']}/wearable/#", ""]
    (ROOT / "services" / "broker" / "acl").write_text("\n".join(lines).rstrip() + "\n")


def device_service(h, cfg):
    noise = cfg["noise"]
    lim = cfg["limits"]
    env = {
        "DEVICE_ROLE": h["role"],
        "MQTT_USERNAME": h["name"],
        "MQTT_PASSWORD": "${%s:?set in .env}" % env_var(h["name"]),
        "BED": str(h["bed"]),
        "HOST_IP": h["ip"],
        # Env SEED overrides the config default so a session can use a distinct seed (e.g. s06);
        # unset -> the config seed, so earlier sessions' semantics are unchanged.
        "SEED": "${SEED:-%s}" % cfg["seed"],
        "SESSION_ID": "${SESSION_ID:-}",
        "REALISM_JITTER": "1" if noise["jitter"] else "0",
        "REALISM_REBOOT": "1" if noise["reboot"] else "0",
        "SAMPLING_DRIFT": str(noise["sampling_drift"]),
        "REBOOT_PER_HOUR": str(noise["reboot_per_hour"]),
    }
    vols = ["./data/raw/sessions:/data/sessions"]
    if "bidmc" in h:
        env["BIDMC_CSV"] = f"/data/physionet/bidmc_{h['bidmc']}_Numerics.csv"
        vols.insert(0, "./data/raw/physionet:/data/physionet:ro")
    if h["role"] == "nurse-station":
        env["BEDS"] = str(cfg["beds"])
        # Empty defaults => nurse.py uses its built-in cadence; dry runs export short values.
        env["NURSE_CMD_INTERVAL"] = "${NURSE_CMD_INTERVAL:-}"
        env["NURSE_RECONNECT_MIN"] = "${NURSE_RECONNECT_MIN:-120}"
        env["NURSE_RECONNECT_MAX"] = "${NURSE_RECONNECT_MAX:-240}"
    return _service(h["name"], image=cfg["images"]["device"], build="./services/devices",
                    env=env, ip=h["ip"], cpus=lim["device_cpus"], mem=lim["device_mem"],
                    depends=["broker"], volumes=vols)


def _service(name, image, env, ip=None, build=None, cpus=None, mem=None, depends=None,
             volumes=None, network_mode=None, cap_add=None, sysctls=None, command=None):
    out = [f"  {name}:"]
    if build:
        out.append(f"    build: {build}")
    out.append(f"    image: {image}")
    if command:
        out.append(f"    command: {command}")
    if env:
        out.append("    environment:")
        for k, v in env.items():
            out.append(f"      {k}: \"{v}\"")
    if volumes:
        out.append("    volumes:")
        out += [f"      - {v}" for v in volumes]
    if depends:
        out.append(f"    depends_on: [{', '.join(depends)}]")
    if network_mode:
        out.append(f"    network_mode: {network_mode}")
    else:
        out += ["    networks:", "      ward_net:", f"        ipv4_address: {ip}"]
    if cap_add:
        out.append(f"    cap_add: [{', '.join(cap_add)}]")
    if sysctls:
        out.append("    sysctls:")
        for k, v in sysctls.items():
            out.append(f"      {k}: \"{v}\"")
    if cpus is not None:
        out.append(f"    cpus: {cpus}")
    if mem is not None:
        out.append(f"    mem_limit: {mem}")
    out.append("    restart: unless-stopped")
    return "\n".join(out)


def generate(cfg):
    hosts = build_hosts(cfg)
    accounts = [h["name"] for h in hosts if h.get("account")]
    net, lim, img = cfg["network"], cfg["limits"], cfg["images"]

    blocks = [
        "# GENERATED by scripts/gen_lab.py from config/ward.json. Do not edit by hand.",
        f"name: wardwatch", "",
        "networks:", "  ward_net:", "    driver: bridge", "    internal: true",
        "    driver_opts:", f"      com.docker.network.bridge.name: {net['bridge']}",
        "    ipam:", "      config:", f"        - subnet: {net['subnet']}", "",
        "services:",
    ]

    broker_env = {env_var(a): "${%s:?set in .env}" % env_var(a) for a in accounts}
    blocks.append(_service("broker", image=img["broker"],
                           command='["sh", "/mosquitto/config/gen_passwd.sh"]',
                           env=broker_env, ip=cfg["broker"]["ip"],
                           cpus=lim["broker_cpus"], mem=lim["broker_mem"],
                           volumes=["./services/broker:/mosquitto/config:ro"]))

    for h in hosts:
        blocks.append(device_service(h, cfg))

    blocks.append(_service("capture", image=img["capture"], build="./services/capture",
                           env={"TZ": "UTC", "SESSION_ID": "${SESSION_ID:-}"},
                           network_mode="host", cap_add=["NET_RAW", "NET_ADMIN"],
                           depends=["broker"], cpus=lim["infra_cpus"], mem=lim["infra_mem"],
                           volumes=["./data/raw/pcap:/data/pcap",
                                    "./data/raw/sessions:/data/sessions"]))

    blocks.append(_service("attacker", image=img["attacker"], build="./services/attacker",
                           env={"SEED": "${SEED:-%s}" % cfg["seed"], "SESSION_ID": "${SESSION_ID:-}"},
                           ip=cfg["attacker"]["ip"], cap_add=["NET_RAW", "NET_ADMIN"],
                           sysctls={"net.ipv4.ip_forward": "1"},
                           cpus=lim["infra_cpus"], mem=lim["infra_mem"],
                           volumes=["./data/raw/sessions:/data/sessions",
                                    "./data/raw/creds:/run/creds:ro",
                                    "./schedules:/schedules:ro",
                                    "./config:/config:ro"]))

    (ROOT / "docker-compose.yml").write_text("\n".join(blocks) + "\n")
    write_creds(write_env(accounts))
    write_accounts(accounts)
    write_acl(hosts, cfg["beds"])
    print(f"generated docker-compose.yml, acl, accounts.txt, .env for {cfg['beds']} beds "
          f"({len(accounts)} MQTT accounts)")


if __name__ == "__main__":
    os.makedirs(ROOT / "schedules", exist_ok=True)
    generate(json.loads(CONFIG.read_text()))
